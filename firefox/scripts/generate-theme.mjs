#!/usr/bin/env node
// Generates firefox/src/theme/tokens.js from the built tokens dist
// (spec §1.4). Deterministic: key order = insertion order of the tokens
// build, so `node scripts/generate-theme.mjs && git diff --exit-code` holds.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..', '..');
const { themePacks, getThemeCssVars } = await import(
  join(repoRoot, 'dist', 'tokens', 'src', 'index.js')
);

const pack = structuredClone(themePacks.monokai);
const cssVars = getThemeCssVars(pack);

// JSON.stringify preserves object insertion order → deterministic output.
const body = `/* Auto-generated by generate-theme.mjs - DO NOT EDIT */
export const themeId = 'monokai';
export const pack = ${JSON.stringify(pack, null, 2)};
export const cssVars = ${JSON.stringify(cssVars, null, 2)};
export function resolveToken(path) {
  let node = pack;
  for (const key of path) {
    if (node === null || typeof node !== 'object' || !(key in node)) {
      throw new Error(\`unknown token path: \${path.join('.')}\`);
    }
    node = node[key];
  }
  if (typeof node !== 'string') {
    throw new Error(\`unknown token path: \${path.join('.')}\`);
  }
  return node;
}
`;

const outDir = join(repoRoot, 'firefox', 'src', 'theme');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'tokens.js'), body);
console.log('Generated firefox/src/theme/tokens.js');
